// Precompiles the JSON Schemas into standalone validator code (Ajv standalone mode), so validation
// never compiles code at runtime. Cloudflare Workers forbid `new Function`, which Ajv's normal
// compile step uses; the admin validates uploads there (R1.3). The schemas stay the source of truth:
// CI regenerates this file and fails if the committed copy differs.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SCHEMAS = {
  manifest: 'manifest',
  calendar: 'calendar',
  holidays: 'holidays',
  businessCalendar: 'business-calendar',
  adminUnits: 'admin-units',
  boundaries: 'boundaries',
} as const;

const load = async (name: string) =>
  JSON.parse(await readFile(join(ROOT, 'schemas', `${name}.schema.json`), 'utf8')) as {
    $id: string;
  };

// Same options as before precompiling: default strict mode, every error reported.
const ajv = new Ajv2020({
  allErrors: true,
  allowUnionTypes: true,
  code: { source: true, esm: true, lines: true },
});
ajv.addSchema(await load('common'));
const exports: Record<string, string> = {};
for (const [exportName, file] of Object.entries(SCHEMAS)) {
  const schema = await load(file);
  ajv.addSchema(schema);
  exports[exportName] = schema.$id;
}

// Ajv's ESM output still loads its runtime helpers with require(); turn those into imports so the
// file is a plain ES module (bundlers and Workers).
const helpers: string[] = [];
const code = standaloneCode(ajv, exports).replace(
  /require\("(ajv\/dist\/runtime\/[a-z0-9]+)"\)\.default/g,
  (_match, path: string) => {
    helpers.push(path);
    return `runtime${helpers.length - 1}`;
  },
);
if (/\brequire\(/.test(code)) throw new Error('Unexpected require() left in the generated code.');
// The helpers are CommonJS with `exports.default`: Node's ESM loader exposes them as
// { default: { default: fn } }, bundlers as { default: fn }. Accept both.
const imports = helpers
  .map(
    (path, i) =>
      `import * as helper${i} from '${path}.js';\n` +
      `const runtime${i} = helper${i}.default.default ?? helper${i}.default;\n`,
  )
  .join('');

const header =
  '// Generated by scripts/build-validators.ts from schemas/*.schema.json. Do not edit.\n' +
  '// @ts-nocheck\n/* eslint-disable */\n';
await writeFile(
  join(ROOT, 'src', 'generated', 'validators.js'),
  header + imports + code.replace(/^"use strict";\n?/, ''),
);
console.log('Wrote src/generated/validators.js');
