// Bundles dataset releases into the SDK (release pinning, ADR 0001):
//   node scripts/bundle.ts <release-dir>...              approved, signed-off real releases (R1.5)
//   node scripts/bundle.ts --synthetic <release-dir>...  synthetic fixtures, for tests only
// Each release is validated with @adhify/release-format first. Without --synthetic, synthetic or
// unapproved releases, and sources that forbid redistribution, are refused.
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { validateRelease } from '@adhify/release-format';
import { readReleaseDir } from '@adhify/release-format/node';

const TYPES = {
  calendar: 'CalendarData',
  holidays: 'HolidaysData',
  'business-calendar': 'BusinessCalendarData',
  'admin-units': 'AdminUnitsData',
} as const;
type Bundled = keyof typeof TYPES;

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'bundle');
const { values, positionals } = parseArgs({
  allowPositionals: true,
  options: { synthetic: { type: 'boolean', default: false } },
});

const seen = new Set<string>();
await mkdir(OUT, { recursive: true });
for (const dir of positionals) {
  const input = await readReleaseDir(resolve(dir));
  const result = await validateRelease(input, { forPublication: !values.synthetic });
  const manifest = result.manifest;
  if (!result.ok || !manifest) {
    for (const issue of result.issues)
      console.error(`${issue.code}\t${issue.path}\t${issue.message}`);
    throw new Error(`${dir} is not a valid release`);
  }
  if (manifest.synthetic && !values.synthetic) throw new Error(`${dir} is synthetic`);
  if (!(manifest.dataset in TYPES))
    throw new Error(`${manifest.dataset} is not bundled in the SDK`);
  const dataset = manifest.dataset as Bundled;
  if (seen.has(dataset)) throw new Error(`two ${dataset} releases given`);
  seen.add(dataset);

  const [file] = manifest.files;
  const data = JSON.parse(new TextDecoder().decode(input.files.get(file!.path)));
  const release = {
    info: {
      dataset,
      version: manifest.version,
      schema_version: manifest.schema_version,
      synthetic: manifest.synthetic === true,
    },
    coverage: { ad_years: manifest.coverage.ad_years, as_of: manifest.coverage.as_of },
    data,
  };
  const source = [
    `// Generated by scripts/bundle.ts from ${dataset}@${manifest.version}. Do not edit.`,
    `import type { ${TYPES[dataset]}, Release } from '../types.ts';`,
    '',
    `export const release: Release<${TYPES[dataset]}> = ${JSON.stringify(release)};`,
    '',
  ].join('\n');
  await writeFile(join(OUT, `${dataset}.ts`), source);
  console.log(`Bundled ${dataset}@${manifest.version}${manifest.synthetic ? ' (synthetic)' : ''}`);
}
for (const dataset of Object.keys(TYPES)) {
  if (!seen.has(dataset)) throw new Error(`no ${dataset} release given; the SDK bundles all four`);
}
